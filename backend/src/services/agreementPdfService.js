/**
 * PDF generation for rental agreements.
 *
 * Library choice: pdf-lib (over pdfkit). The signing flow stamps each
 * party's signature onto the EXISTING stored PDF, one signature at a time —
 * pdfkit can only create documents from scratch, which would force us to
 * persist raw signature image data just to re-render earlier signatures.
 * pdf-lib both creates and edits PDFs, so signature images live only in the
 * request that carries them and in the stamped PDF itself.
 *
 * "Digital signature" scope (MVP): a typed/drawn signature captured by the
 * frontend as a base64 PNG/JPEG image, stamped visually into the PDF with a
 * timestamp. This is NOT a cryptographic (PKI) signature and carries no
 * cryptographic guarantees.
 */
const { PDFDocument, StandardFonts, rgb } = require('pdf-lib');

const PAGE = { width: 595, height: 842 }; // A4 portrait

// Fixed slots the signature stamps land in (pdf-lib y-axis is bottom-up).
const SIGNATURE_SLOTS = {
  tenant: { x: 72, y: 150 },
  landlord: { x: 330, y: 150 },
};

const formatDate = (d) =>
  new Date(d).toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'long',
    year: 'numeric',
  });

/**
 * Builds the initial (unsigned) agreement PDF. Returns a Buffer.
 */
const generateAgreementPdf = async (agreementData) => {
  const {
    agreementNumber,
    tenantName,
    landlordName,
    propertyTitle,
    propertyAddress,
    monthlyRent,
    deposit,
    startDate,
    endDate,
  } = agreementData;

  const doc = await PDFDocument.create();
  const page = doc.addPage([PAGE.width, PAGE.height]);
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);

  let y = PAGE.height - 72;
  const text = (str, opts = {}) => {
    page.drawText(str, {
      x: opts.x ?? 72,
      y,
      size: opts.size ?? 11,
      font: opts.bold ? bold : font,
      color: rgb(0.1, 0.1, 0.1),
    });
    y -= opts.gap ?? 20;
  };

  text('RENTAL AGREEMENT', { size: 20, bold: true, x: 195, gap: 14 });
  page.drawLine({
    start: { x: 72, y },
    end: { x: PAGE.width - 72, y },
    thickness: 1,
    color: rgb(0.6, 0.6, 0.6),
  });
  y -= 26;

  text(`Agreement Number: ${agreementNumber}`, { bold: true, gap: 30 });

  text('1. PARTIES', { bold: true });
  text(`This rental agreement is made between ${landlordName} (the "Landlord")`);
  text(`and ${tenantName} (the "Tenant").`, { gap: 28 });

  text('2. PROPERTY', { bold: true });
  text(`Property: ${propertyTitle}`);
  text(`Address: ${propertyAddress}`, { gap: 28 });

  text('3. TERM', { bold: true });
  text(`The tenancy begins on ${formatDate(startDate)} and ends on ${formatDate(endDate)}.`, { gap: 28 });

  text('4. RENT AND DEPOSIT', { bold: true });
  text(`Monthly rent: Rs. ${Number(monthlyRent).toLocaleString('en-IN')}, payable in advance.`);
  text(
    deposit
      ? `Security deposit: Rs. ${Number(deposit).toLocaleString('en-IN')}, refundable per the terms herein.`
      : 'Security deposit: as mutually agreed between the parties.',
    { gap: 28 }
  );

  text('5. GENERAL TERMS', { bold: true });
  text('The Tenant shall use the property for residential purposes only, keep it in');
  text('good condition, and return it in the same condition at the end of the term.');
  text('Either party may terminate with notice as per applicable law. This document');
  text('was generated by the VeriNest platform.', { gap: 30 });

  // Signature section — stamps land in the boxes below when parties sign.
  text('IN WITNESS WHEREOF, the parties have signed this agreement:', { bold: true });

  for (const [party, slot] of Object.entries(SIGNATURE_SLOTS)) {
    page.drawRectangle({
      x: slot.x,
      y: slot.y,
      width: 190,
      height: 70,
      borderColor: rgb(0.6, 0.6, 0.6),
      borderWidth: 1,
    });
    page.drawText(party === 'tenant' ? `Tenant: ${tenantName}` : `Landlord: ${landlordName}`, {
      x: slot.x,
      y: slot.y - 16,
      size: 10,
      font,
      color: rgb(0.1, 0.1, 0.1),
    });
  }

  return Buffer.from(await doc.save());
};

/**
 * Stamps a signature image (base64 PNG/JPEG, data-URI prefix optional) onto
 * an EXISTING agreement PDF in that party's slot, with a timestamp line.
 * Returns the updated PDF as a Buffer.
 */
const stampSignature = async (pdfBuffer, signatureBase64, party) => {
  const slot = SIGNATURE_SLOTS[party];
  if (!slot) throw new Error(`Unknown signing party: ${party}`);

  const doc = await PDFDocument.load(pdfBuffer);
  const page = doc.getPage(0);
  const font = await doc.embedFont(StandardFonts.Helvetica);

  const base64 = signatureBase64.replace(/^data:image\/(png|jpe?g);base64,/, '');
  const imageBytes = Buffer.from(base64, 'base64');
  const image =
    imageBytes[0] === 0x89
      ? await doc.embedPng(imageBytes)
      : await doc.embedJpg(imageBytes);

  // Fit the signature inside the slot box, preserving aspect ratio.
  const scale = Math.min(180 / image.width, 60 / image.height, 1);
  page.drawImage(image, {
    x: slot.x + 5,
    y: slot.y + 8,
    width: image.width * scale,
    height: image.height * scale,
  });
  page.drawText(`Signed digitally on ${new Date().toISOString()}`, {
    x: slot.x,
    y: slot.y - 30,
    size: 8,
    font,
    color: rgb(0.35, 0.35, 0.35),
  });

  return Buffer.from(await doc.save());
};

module.exports = { generateAgreementPdf, stampSignature };
